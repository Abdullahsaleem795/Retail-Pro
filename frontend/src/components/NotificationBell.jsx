import { useState, useEffect, useRef, useCallback } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { FiBell } from 'react-icons/fi';
import toast from 'react-hot-toast';
import {
  listNotifications,
  markNotificationRead,
  markAllNotificationsRead,
  deleteNotification,
} from '../api/notifications';
import { formatDateTime } from '../utils/format';
import './NotificationBell.css';

const TYPE_LABELS = {
  low_stock: 'Low Stock',
  daily_report: 'Daily Report',
  weekly_report: 'Weekly Report',
  expiry: 'Expiry',
  payment_due: 'Payment Due',
  system: 'System',
  subscription: 'Subscription',
};

export default function NotificationBell() {
  const [open, setOpen] = useState(false);
  const [notifications, setNotifications] = useState([]);
  const [unreadCount, setUnreadCount] = useState(0);
  const [loading, setLoading] = useState(false);
  const containerRef = useRef(null);

  const fetchNotifications = useCallback(async () => {
    try {
      const res = await listNotifications();
      setNotifications(res.data);
      setUnreadCount(res.unreadCount);
    } catch {
      // Silent - a failed poll shouldn't interrupt the cashier mid-sale
    }
  }, []);

  useEffect(() => {
    fetchNotifications();
    // Reports are generated by backend cron, so a slow poll is plenty
    const interval = setInterval(fetchNotifications, 120000);
    return () => clearInterval(interval);
  }, [fetchNotifications]);

  // Close on outside click
  useEffect(() => {
    if (!open) return undefined;
    const handleClick = (e) => {
      if (containerRef.current && !containerRef.current.contains(e.target)) setOpen(false);
    };
    document.addEventListener('mousedown', handleClick);
    return () => document.removeEventListener('mousedown', handleClick);
  }, [open]);

  const handleToggle = async () => {
    const next = !open;
    setOpen(next);
    if (next) {
      setLoading(true);
      await fetchNotifications();
      setLoading(false);
      // Opening the panel counts as having seen them - clear the badge the
      // moment they're visibly on screen, instead of waiting on a
      // round-trip to the server. Applied after the fetch above (which
      // would otherwise overwrite it with the still-unread count from
      // before this "read" state has actually landed server-side).
      setNotifications((prev) => prev.map((n) => ({ ...n, isRead: true })));
      setUnreadCount(0);
      // Persisting is a background sync concern from here - whether it
      // succeeds or hits a transient network hiccup, the shopkeeper never
      // asked to "mark all as read", they just opened the bell, so a
      // failure here shouldn't surface as an error about an action they
      // didn't take.
      handleMarkAll({ silent: true });
    }
  };

  const handleRead = async (notification) => {
    if (notification.isRead) return;
    // Optimistic: the badge should drop the moment it's tapped
    setNotifications((prev) => prev.map((n) => (n._id === notification._id ? { ...n, isRead: true } : n)));
    setUnreadCount((c) => Math.max(c - 1, 0));
    try {
      await markNotificationRead(notification._id);
    } catch {
      fetchNotifications(); // roll back to server truth
    }
  };

  const handleDelete = async (notification, e) => {
    e.stopPropagation();
    const wasUnread = !notification.isRead;
    setNotifications((prev) => prev.filter((n) => n._id !== notification._id));
    if (wasUnread) setUnreadCount((c) => Math.max(c - 1, 0));
    try {
      await deleteNotification(notification._id);
    } catch {
      toast.error('Could not delete notification');
      fetchNotifications(); // roll back to server truth
    }
  };

  const handleMarkAll = async ({ silent = false } = {}) => {
    setNotifications((prev) => prev.map((n) => ({ ...n, isRead: true })));
    setUnreadCount(0);
    try {
      await markAllNotificationsRead();
    } catch {
      // Silent path (auto-triggered by opening the bell): the shopkeeper
      // never asked for this write, so a transient failure shouldn't
      // interrupt them - the next open/poll will just try again.
      if (!silent) toast.error('Could not mark all as read');
    }
  };

  return (
    <div className="notif-wrap" ref={containerRef}>
      <button className="notif-bell" onClick={handleToggle} aria-label="Notifications">
        <FiBell size={18} aria-hidden="true" />
        {unreadCount > 0 && <span className="notif-badge">{unreadCount > 9 ? '9+' : unreadCount}</span>}
      </button>

      <AnimatePresence>
        {open && (
          <motion.div
            className="notif-panel"
            initial={{ opacity: 0, y: -6 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: -6 }}
            transition={{ duration: 0.15 }}
          >
            <div className="notif-head">
              <span>Notifications</span>
              {unreadCount > 0 && (
                <button className="btn-link" onClick={handleMarkAll}>Mark all read</button>
              )}
            </div>

            <div className="notif-list">
              {loading ? (
                <p className="notif-empty">Loading...</p>
              ) : notifications.length === 0 ? (
                <p className="notif-empty">No notifications yet. Stock alerts and daily reports will appear here.</p>
              ) : (
                notifications.map((n) => (
                  <div
                    key={n._id}
                    role="button"
                    tabIndex={0}
                    className={n.isRead ? 'notif-item' : 'notif-item notif-item-unread'}
                    onClick={() => handleRead(n)}
                    onKeyDown={(e) => e.key === 'Enter' && handleRead(n)}
                  >
                    <div className="notif-item-top">
                      <span className="notif-type">{TYPE_LABELS[n.type] || n.type}</span>
                      <div className="notif-item-top-right">
                        <span className="notif-time">{formatDateTime(n.createdAt)}</span>
                        <button
                          className="notif-delete"
                          aria-label="Delete notification"
                          onClick={(e) => handleDelete(n, e)}
                        >
                          ×
                        </button>
                      </div>
                    </div>
                    <span className="notif-title">{n.title}</span>
                    {n.channel === 'whatsapp' && (
                      <span className={`notif-status notif-status-${n.deliveryStatus}`}>
                        WhatsApp: {n.deliveryStatus}
                      </span>
                    )}
                  </div>
                ))
              )}
            </div>
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
}
